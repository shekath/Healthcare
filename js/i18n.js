export const STRINGS = S;
export const isAr = () => state.lang === 'ar';

const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩';
/** Arabic-Indic digits in Arabic mode (as the design does), Latin otherwise. */
export function num(v) {
  const s = String(v);
  if (!isAr()) return s;
  return s.replace(/[0-9]/g, d => AR_DIGITS[d]).replace(/\./g, '٫');
}

export function t(key, vars) {
  const dict = S[state.lang] || S.en;
  let s = dict[key];
  if (s === undefined) s = S.en[key];
  if (s === undefined) { console.warn('[i18n] missing', key); return key; }
  if (vars && typeof s === 'string') {
    s = s.replace(/\{(\w+)\}/g, (_, k) => {
      const v = vars[k];
      if (v === undefined) return '';
      return typeof v === 'number' ? num(v) : v;
    });
  }
  return s;
}

/** Localised value of a bilingual {en, ar} object. */
export function L(o) {
  if (o == null) return '';
  if (typeof o === 'string') return o;
  return (isAr() ? o.ar : o.en) ?? o.en ?? '';
}
